// errorgen generates scoped Kratos error helpers without changing wire reasons.
package main

import (
	"strings"

	kratosErrors "github.com/go-kratos/kratos/v2/errors"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
)

func main() {
	protogen.Options{}.Run(func(plugin *protogen.Plugin) error {
		plugin.SupportedFeatures = 1
		for _, file := range plugin.Files {
			if !file.Generate {
				continue
			}
			var enums []*protogen.Enum
			var collect func([]*protogen.Message)
			collect = func(messages []*protogen.Message) {
				for _, message := range messages {
					enums = append(enums, message.Enums...)
					collect(message.Messages)
				}
			}
			enums = append(enums, file.Enums...)
			collect(file.Messages)
			var output *protogen.GeneratedFile
			for _, enum := range enums {
				if !proto.HasExtension(enum.Desc.Options(), kratosErrors.E_DefaultCode) {
					continue
				}
				if output == nil {
					output = plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+"_errors.pb.go", file.GoImportPath)
					output.P("// Code generated by platform/tools/errorgen. DO NOT EDIT.")
					output.P("package ", file.GoPackageName)
				}
				prefix := strings.TrimSuffix(string(enum.Desc.Parent().Name()), "Errors")
				defaultCode := proto.GetExtension(enum.Desc.Options(), kratosErrors.E_DefaultCode).(int32)
				for _, value := range enum.Values {
					code := defaultCode
					if proto.HasExtension(value.Desc.Options(), kratosErrors.E_Code) {
						code = proto.GetExtension(value.Desc.Options(), kratosErrors.E_Code).(int32)
					}
					name := prefix + camel(string(value.Desc.Name()))
					output.P("func Is", name, "(err error) bool {")
					output.P("if err == nil { return false }")
					output.P("value := ", output.QualifiedGoIdent(protogen.GoIdent{GoName: "FromError", GoImportPath: "github.com/go-kratos/kratos/v2/errors"}), "(err)")
					output.P("return value.Code == ", code, " && value.Reason == ", value.GoIdent, ".String() }")
					output.P("func Error", name, "(format string, args ...any) *", output.QualifiedGoIdent(protogen.GoIdent{GoName: "Error", GoImportPath: "github.com/go-kratos/kratos/v2/errors"}), " {")
					output.P("return ", output.QualifiedGoIdent(protogen.GoIdent{GoName: "New", GoImportPath: "github.com/go-kratos/kratos/v2/errors"}), "(", code, ",", value.GoIdent, ".String(),", output.QualifiedGoIdent(protogen.GoIdent{GoName: "Sprintf", GoImportPath: "fmt"}), "(format,args...)) }")
				}
			}
		}
		return nil
	})
}

func camel(value string) string {
	var result strings.Builder
	for _, part := range strings.Split(strings.ToLower(value), "_") {
		if part != "" {
			result.WriteString(strings.ToUpper(part[:1]))
			result.WriteString(part[1:])
		}
	}
	return result.String()
}
