package main

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

type schema struct {
	plugin      *protogen.Plugin
	messages    map[string]*protogen.Message
	enums       map[string]*protogen.Enum
	rpcServices map[string]*protogen.Service
}

func newSchema(files *descriptorpb.FileDescriptorSet) (*schema, error) {
	plugin, err := (protogen.Options{}).New(&pluginpb.CodeGeneratorRequest{ProtoFile: files.File})
	if err != nil {
		return nil, err
	}
	s := &schema{
		plugin:      plugin,
		messages:    make(map[string]*protogen.Message),
		enums:       make(map[string]*protogen.Enum),
		rpcServices: make(map[string]*protogen.Service),
	}
	var visit func(*protogen.Message)
	visit = func(message *protogen.Message) {
		s.messages["."+string(message.Desc.FullName())] = message
		for _, enum := range message.Enums {
			s.enums["."+string(enum.Desc.FullName())] = enum
		}
		for _, nested := range message.Messages {
			visit(nested)
		}
	}
	for _, file := range plugin.Files {
		if string(file.Desc.Package()) == "operator.v1" {
			for _, service := range file.Services {
				s.rpcServices[service.GoName] = service
			}
		}
		for _, message := range file.Messages {
			visit(message)
		}
		for _, enum := range file.Enums {
			s.enums["."+string(enum.Desc.FullName())] = enum
		}
	}
	return s, nil
}

func (s *schema) message(g *protogen.GeneratedFile, name string) (string, error) {
	m := s.messages[name]
	if m == nil {
		return "", fmt.Errorf("unknown message %s", name)
	}
	return g.QualifiedGoIdent(m.GoIdent), nil
}

func generated(g *protogen.GeneratedFile, pkg string) {
	g.P("// Code generated by platform/tools/httpgen from independent API and RPC IDL. DO NOT EDIT.")
	g.P("package ", pkg)
}

func qualified(g *protogen.GeneratedFile, path, name string) string {
	return g.QualifiedGoIdent(protogen.GoIdent{
		GoName:       name,
		GoImportPath: protogen.GoImportPath(path),
	})
}

func rpcOperation(binding httpBinding) string {
	return "/operator.v1." + binding.service + "/" + binding.rpc
}

func fullName(descriptor protoreflect.Descriptor) string {
	return "." + string(descriptor.FullName())
}

func apiMessage(name string) bool {
	return strings.HasPrefix(name, ".admin.v1.") || strings.HasPrefix(name, ".google.protobuf.")
}
