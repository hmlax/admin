// httpgen generates explicit adapters between independently owned API and RPC contracts.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
)

const apiModelPath = "go-admin/admin/biz/model/admin/v1"
const handlerPath = "go-admin/admin/biz/handler"
const transportPath = "go-admin/admin/internal/transport"
const operatorPath = "go-admin/platform/pb/operator"

func writeGenerated(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0644)
}

func main() {
	descriptor := flag.String("descriptor", "", "buf descriptor set")
	output := flag.String("out", "admin/biz/handler/bindings_generated.go", "HTTP binding output")
	projectionOutput := flag.String("http-descriptor", "", "API-only descriptor for OpenAPI and TypeScript")
	assetsOnly := flag.Bool("assets-only", false, "generate only asset descriptors")
	flag.Parse()
	wire, err := os.ReadFile(*descriptor)
	if err != nil {
		panic(err)
	}
	files := new(descriptorpb.FileDescriptorSet)
	if err := proto.Unmarshal(wire, files); err != nil {
		panic(err)
	}
	projected, bindings, err := resolveHTTP(files)
	if err != nil {
		panic(err)
	}
	if !*assetsOnly {
		s, err := newSchema(files)
		if err != nil {
			panic(err)
		}
		contracts, err := generateContracts(s, bindings)
		if err != nil {
			panic(err)
		}
		for name, content := range contracts {
			if err := writeGenerated("admin/biz/model/admin/v1/"+name, content); err != nil {
				panic(err)
			}
		}
		helpers, err := generateBindings(s, bindings)
		if err != nil {
			panic(err)
		}
		if err := writeGenerated(*output, helpers); err != nil {
			panic(err)
		}
		if err := generateAdapters(s, bindings); err != nil {
			panic(err)
		}
		operations, err := generateOperations(s)
		if err != nil {
			panic(err)
		}
		if err := writeGenerated("platform/pb/operator/rpc_operations_generated.go", operations); err != nil {
			panic(err)
		}
	}
	if *projectionOutput != "" {
		data, err := proto.Marshal(projected)
		if err != nil {
			panic(err)
		}
		if err := writeGenerated(*projectionOutput, data); err != nil {
			panic(err)
		}
	}
	fmt.Printf("Validated %d independent admin HTTP bindings; routes are generated by hz update.\n", len(bindings))
}

func services(bindings []httpBinding) map[string][]httpBinding {
	out := make(map[string][]httpBinding)
	seen := make(map[string]bool)
	for _, b := range bindings {
		key := b.service + "." + b.method
		if !seen[key] {
			out[b.service] = append(out[b.service], b)
			seen[key] = true
		}
	}
	return out
}
func serviceNames(groups map[string][]httpBinding) []string {
	names := make([]string, 0, len(groups))
	for name := range groups {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
func snake(name string) string {
	var out strings.Builder
	for i, r := range name {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				out.WriteByte('_')
			}
			r += 'a' - 'A'
		}
		out.WriteRune(r)
	}
	return out.String()
}
func generateContracts(s *schema, bindings []httpBinding) (map[string][]byte, error) {
	result := make(map[string][]byte)
	groups := services(bindings)
	for _, name := range serviceNames(groups) {
		g := s.plugin.NewGeneratedFile("contract_"+name+".go", protogen.GoImportPath(apiModelPath))
		generated(g, "adminpb")
		context := qualified(g, "context", "Context")
		for _, b := range groups[name] {
			g.P("const Operation", name, b.method, " = ", fmt.Sprintf("%q", rpcOperation(b)))
			if b.stream {
				g.P("const ", name, b.method, "HTTPPath = ", fmt.Sprintf("%q", httpPath(b.path)))
			}
		}
		g.P("type ", name, "HTTPServer interface {")
		for _, b := range groups[name] {
			input, err := s.message(g, b.input)
			if err != nil {
				return nil, err
			}
			output, err := s.message(g, b.output)
			if err != nil {
				return nil, err
			}
			if b.stream {
				g.P(b.method, "(", context, ",*", input, ",func(*", output, ")error)error")
			} else {
				g.P(b.method, "(", context, ",*", input, ")(*", output, ",error)")
			}
		}
		g.P("}")
		content, err := g.Content()
		if err != nil {
			return nil, err
		}
		result[snake(name)+"_http.pb.go"] = content
	}
	return result, nil
}
func generateBindings(s *schema, bindings []httpBinding) ([]byte, error) {
	g := s.plugin.NewGeneratedFile("bindings_generated.go", protogen.GoImportPath(handlerPath))
	generated(g, "handler")
	context := qualified(g, "context", "Context")
	requestContext := qualified(g, "github.com/cloudwego/hertz/pkg/app", "RequestContext")
	groups := services(bindings)
	for _, name := range serviceNames(groups) {
		for _, b := range groups[name] {
			input, err := s.message(g, b.input)
			if err != nil {
				return nil, err
			}
			iface := qualified(g, apiModelPath, name+"HTTPServer")
			binding := qualified(g, transportPath, "Binding")
			g.P("func Bind", name, b.method, "(service ", iface, ") ", binding, " { return ", binding, "{")
			g.P("Operation:", qualified(g, apiModelPath, "Operation"+name+b.method), ",")
			g.P("Stream:", b.stream, ",")
			g.P("Handler:func(ctx ", context, ", c *", requestContext, "){")
			g.P("in:=new(", input, ")")
			g.P("if err:=", qualified(g, transportPath, "BindRequest"), "(c,in,", fmt.Sprintf("%q", b.body), ");err!=nil{", qualified(g, transportPath, "FailRequest"), "(c,err);return}")
			g.P("if err:=", qualified(g, transportPath, "ValidateRequest"), "(in);err!=nil{", qualified(g, transportPath, "FailRequest"), "(c,err);return}")
			if b.stream {
				output, err := s.message(g, b.output)
				if err != nil {
					return nil, err
				}
				g.P("started:=false")
				g.P("err:=service.", b.method, "(ctx,in,func(frame *", output, ")error{return ", qualified(g, transportPath, "WriteEvent"), "(c,frame,&started)})")
				g.P("if err!=nil{if !started{", qualified(g, transportPath, "FailRequest"), "(c,err)}else{", qualified(g, transportPath, "LogStreamError"), "(ctx,err)}}")
			} else {
				g.P("reply,err:=service.", b.method, "(ctx,in);if err!=nil{", qualified(g, transportPath, "FailRequest"), "(c,err);return}")
				g.P("if err:=", qualified(g, transportPath, "EncodeAPIResponse"), "(c,reply);err!=nil{", qualified(g, transportPath, "FailRequest"), "(c,err)}")
			}
			g.P("},}}")
		}
	}
	return g.Content()
}
func generateOperations(s *schema) ([]byte, error) {
	g := s.plugin.NewGeneratedFile("rpc_operations_generated.go", protogen.GoImportPath(operatorPath))
	generated(g, "operatorpb")
	for _, file := range s.plugin.Files {
		if string(file.Desc.Package()) != "operator.v1" {
			continue
		}
		for _, svc := range file.Services {
			for _, method := range svc.Methods {
				g.P("const Operation", svc.GoName, method.GoName, " = ", fmt.Sprintf("%q", "/"+string(svc.Desc.FullName())+"/"+string(method.Desc.Name())))
			}
		}
	}
	return g.Content()
}
