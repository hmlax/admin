// protoc-gen-gorm-model generates persistence models from protobuf definitions.
// Unlike RPC messages, persistence timestamps use time.Time and JSON columns use
// native typed values, so GORM can scan them without protobuf runtime internals.
package main

import (
	"fmt"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/srikrsna/protoc-gen-gotag/tagger"

	operatorV1 "go-admin/platform/pb/operator"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
)

func main() {
	protogen.Options{}.Run(func(plugin *protogen.Plugin) error {
		plugin.SupportedFeatures = 1 // proto3 optional
		for _, file := range plugin.Files {
			if file.Generate {
				for _, message := range file.Messages {
					message.GoIdent.GoName = string(message.Desc.Name())
				}
			}
		}
		for _, file := range plugin.Files {
			if !file.Generate {
				continue
			}
			if err := generate(plugin, file); err != nil {
				return err
			}
		}
		return generateQueries(plugin)
	})
}

func generate(plugin *protogen.Plugin, file *protogen.File) error {
	g := plugin.NewGeneratedFile("platform/pb/operator/"+filepath.Base(file.GeneratedFilenamePrefix)+".gorm.pb.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-gorm-model. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P("package ", file.GoPackageName)
	for _, message := range file.Messages {
		if !proto.HasExtension(message.Desc.Options(), operatorV1.E_Model) {
			return fmt.Errorf("%s: missing persistence.model option", message.Desc.FullName())
		}
		g.P(message.Comments.Leading)
		g.P("type ", message.GoIdent, " struct {")
		for _, field := range message.Fields {
			tags, ok := proto.GetExtension(field.Desc.Options(), tagger.E_Tags).(string)
			if !ok || !strings.Contains(tags, "gorm:") || strings.Contains(tags, "`") {
				return fmt.Errorf("%s: valid gorm tag required", field.Desc.FullName())
			}
			minLen, _ := proto.GetExtension(field.Desc.Options(), operatorV1.E_MinLen).(uint64)
			maxLen, _ := proto.GetExtension(field.Desc.Options(), operatorV1.E_MaxLen).(uint64)
			immutable, _ := proto.GetExtension(field.Desc.Options(), operatorV1.E_Immutable).(bool)
			tags += " orm_min_len:" + strconv.Quote(strconv.FormatUint(minLen, 10)) + " orm_max_len:" + strconv.Quote(strconv.FormatUint(maxLen, 10)) + " orm_immutable:" + strconv.Quote(strconv.FormatBool(immutable))
			enums, _ := proto.GetExtension(field.Desc.Options(), operatorV1.E_EnumValues).([]*operatorV1.EnumValue)
			if len(enums) > 0 {
				var allowed []string
				for _, value := range enums {
					allowed = append(allowed, value.Value)
				}
				tags += " orm_enum:" + strconv.Quote(strings.Join(allowed, ","))
			}
			g.P(field.Comments.Leading)
			g.P(goName(field), " ", nativeType(g, field), " `", tags, "`")
		}
		model := proto.GetExtension(message.Desc.Options(), operatorV1.E_Model).(*operatorV1.Model)
		for _, relation := range model.GetRelations() {
			target := "*" + relation.GetTarget()
			if relation.GetMany() {
				target = "[]" + target
			}
			g.P(relation.GetName(), " ", target, " `gorm:", strconv.Quote("foreignKey:"+relation.GetForeignKey()+";references:"+relation.GetReferences()), " json:\"-\"`")
		}
		g.P("}")
		g.P()
		for _, field := range message.Fields {
			typ := nativeType(g, field)
			optional := field.Desc.HasOptionalKeyword() && field.Desc.Kind() != protoreflect.MessageKind && field.Desc.Kind() != protoreflect.BytesKind
			if optional {
				typ = strings.TrimPrefix(typ, "*")
			}
			g.P("func (x *", message.GoIdent, ") Get", field.GoName, "() ", typ, " {")
			if optional {
				g.P("if x != nil && x.", goName(field), " != nil { return *x.", goName(field), " }")
			} else {
				g.P("if x != nil { return x.", goName(field), " }")
			}
			g.P("var zero ", typ, ";return zero }")
		}
	}
	return nil
}

func goName(field *protogen.Field) string {
	if name, ok := proto.GetExtension(field.Desc.Options(), operatorV1.E_GoName).(string); ok && name != "" {
		return name
	}
	return field.GoName
}

func nativeType(g *protogen.GeneratedFile, field *protogen.Field) string {
	var name string
	switch field.Desc.Kind() {
	case protoreflect.BoolKind:
		name = "bool"
	case protoreflect.StringKind:
		name = "string"
	case protoreflect.BytesKind:
		return "[]byte"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		name = "int32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		name = "int64"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		name = "uint32"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		name = "uint64"
	case protoreflect.FloatKind:
		name = "float32"
	case protoreflect.DoubleKind:
		name = "float64"
	case protoreflect.MessageKind:
		if field.Message.Desc.FullName() == "google.protobuf.Timestamp" {
			return "*" + g.QualifiedGoIdent(protogen.GoIdent{GoName: "Time", GoImportPath: "time"})
		}
		return "*" + g.QualifiedGoIdent(field.Message.GoIdent)
	default:
		panic(fmt.Sprintf("unsupported persistence type: %s", field.Desc.FullName()))
	}
	if field.Desc.IsList() {
		return "[]" + name
	}
	if field.Desc.HasOptionalKeyword() {
		return "*" + name
	}
	return name
}
